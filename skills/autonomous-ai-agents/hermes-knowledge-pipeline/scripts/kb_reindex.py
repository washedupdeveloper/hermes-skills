#!/usr/bin/env python3
"""kb_reindex.py - deterministic vault indexer. Zero LLM calls.

Regenerates `index.md` and `_meta/orient.json`, writes `_meta/kb-index.json`, and
reports only genuine problems. Safe to run hourly from a --no-agent cron job.

The vault is an ITERATIVE research corpus: research accumulates as knowledge, and
superseded knowledge is archived rather than deleted, so a later iteration can see
what was believed before and why it changed. `_archive/` is therefore a first-class
part of the model, not a bin.

Design rules this file obeys
----------------------------
* **Silent when healthy.** stdout is the alarm channel. Normal steady state
  (pending proposals, low-confidence pages, staleness, archived iterations) is
  STATE and lives in orient.json, never in the findings list. A check that fires
  on a healthy vault trains its reader to ignore it.
* **Generated, not hand-maintained.** `index.md` is written here. Two
  hand-maintained copies of one catalogue drift apart - the same defect class as
  two env vars pointing at one path.
* **Structure is parsed as structure.** The tag taxonomy and schema version live
  in a machine-readable block inside SCHEMA.md, not in prose to be regexed.
* **Tolerant links.** An LLM naturally writes `[[Hermes Agent]]`, not
  `[[entities/hermes-agent]]`. Slug, basename, title and Obsidian `aliases:` all
  resolve, case- and separator-insensitively.
* **No third-party imports.** The Hermes python ships no PyYAML, so frontmatter
  is read by a small deterministic YAML-subset parser.

Usage:
    kb_reindex.py [root]            regenerate outputs, report findings
    kb_reindex.py [root] --orient   print orientation, write nothing
"""
from __future__ import annotations

import datetime
import hashlib
import json
import os
import re
import sys
from pathlib import Path

__version__ = "3.0.0"

CANONICAL_DIRS = ("entities", "concepts", "comparisons", "queries")
# `work/` is the supervisor's board: one page per unit of in-flight work. It is a
# first-class page directory but NOT canonical knowledge - its pages are ephemeral
# by design and are never promoted into the corpus.
WORK_DIR = "work"
PAGE_DIRS = CANONICAL_DIRS + ("inbox", WORK_DIR)
ARCHIVE_DIR = "_archive"
RAW_DIRS = ("raw",)
REQUIRED_FM = ("title", "created", "updated", "type", "tags", "sources", "status")
# Work items carry the fields a Kanban board groups and filters on. Required, not
# optional: a board with blank columns and missing priorities is a board nobody
# trusts, and an unchecked convention is a decorative one.
WORK_REQUIRED = ("status", "priority", "owner", "topic")
WORK_STATUSES = ("backlog", "active", "blocked", "done")
WORK_PRIORITIES = ("P0", "P1", "P2", "P3")
WORK_OWNERS = ("agent", "human", "council")
MAX_LINES = 200
STALE_DAYS = 180
LIVE_STATUSES = ("proposed", "approved")

# Explicit map, not `dir.rstrip('s')` - that turns 'entities' into 'entitie'.
DIR_TYPE = {"entities": "entity", "concepts": "concept",
            "comparisons": "comparison", "queries": "query",
            WORK_DIR: "work"}

LINK_RE = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")
FM_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.DOTALL)
FENCE_RE = re.compile(r"```.*?```", re.DOTALL)
INLINE_CODE_RE = re.compile(r"`[^`\n]*`")
SCHEMA_BLOCK_RE = re.compile(r"```ya?ml[ \t]*\r?\n(.*?)```", re.DOTALL)
LOG_ENTRY_RE = re.compile(r"^##\s*\[(\d{4}-\d{2}-\d{2})\]\s*([A-Za-z]+)\s*\|\s*(.+?)\s*$",
                          re.MULTILINE)
INDEX_BANNER = (
    "<!-- generated by kb_reindex.py - do not edit by hand.\n"
    "     Edit the pages, SCHEMA.md or log.md instead; this file is rebuilt from\n"
    "     them by the hourly kb-reindex job. -->\n"
)

# --------------------------------------------------------------------------- #
# Frontmatter (YAML subset - no PyYAML available in the Hermes python)
# --------------------------------------------------------------------------- #


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def _scalar(value: str):
    value = value.strip()
    if value.startswith("[") and value.endswith("]"):
        return [x for x in (_unquote(p) for p in value[1:-1].split(",")) if x]
    return _unquote(value)


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """(frontmatter, body). Handles scalars, inline lists and block lists.

    Multi-line block scalars (`|` / `>`) are not supported - keep frontmatter to
    scalars and lists and this stays exact.
    """
    m = FM_RE.match(text)
    if not m:
        return {}, text
    fm: dict = {}
    lines = m.group(1).splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        i += 1
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line[0] in " \t":
            continue  # stray continuation; block lists are consumed below
        key, sep, raw = line.partition(":")
        if not sep:
            continue
        key, raw = key.strip(), raw.strip()
        if raw == "":
            items = []
            while i < len(lines) and re.match(r"^\s+-\s+", lines[i]):
                items.append(_unquote(lines[i].strip()[1:].strip()))
                i += 1
            fm[key] = items
        else:
            fm[key] = _scalar(raw)
    return fm, text[m.end():]


def as_list(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(v).strip() for v in value if str(v).strip()]
    return [str(value).strip()] if str(value).strip() else []


# Canonical frontmatter field order, and the single writer for it. kb_archive.py and
# kb_promote.py both rewrite frontmatter; a second copy of this renderer in either of
# them is the drift defect this pipeline exists to avoid.
FM_ORDER = ["title", "created", "updated", "type", "tags", "sources", "confidence",
            "status", "proposed_by", "aliases", "supersedes", "superseded_by",
            "archived", "contested", "contradictions"]


# Plain scalars YAML would reinterpret: a bare `true`, `12` or `~` becomes a
# bool/number/null, silently changing a property's type across the whole vault.
_YAML_RESERVED = {"true", "false", "yes", "no", "on", "off", "null", "~", "none"}
_NUMERIC_RE = re.compile(r"^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$")
_INDICATORS = "-?:,[]{}#&*!|>'\"%@`"


def yaml_scalar(value) -> str:
    """This value as a string that parses back as exactly this value.

    Naive interpolation is how `title: council: infra` reaches the disk: a `: `
    inside an unquoted scalar is a YAML syntax error, so a page whose title happens to
    contain a colon becomes an unparseable file - and frontmatter is what every
    downstream reader, including Bases, trusts. Quote only what must be quoted, so
    ordinary words stay bare and no existing page churns. Dates in particular MUST
    stay unquoted (`2026-10-07T09:40:47`) or Obsidian types the property as text and
    date arithmetic silently stops working.
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    s = str(value)
    if s == "":
        return '""'
    unsafe = (
        s != s.strip()
        or any(c in s for c in "\n\t")
        or ": " in s
        or s.endswith(":")
        or " #" in s
        or s[0] in _INDICATORS
        or s.lower() in _YAML_RESERVED
        or bool(_NUMERIC_RE.match(s))
    )
    if not unsafe:
        return s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_frontmatter(fm: dict) -> str:
    """Serialise frontmatter in a stable field order. Lists stay inline."""
    keys = [k for k in FM_ORDER if k in fm] + sorted(k for k in fm if k not in FM_ORDER)
    out = ["---\n"]
    for k in keys:
        v = fm[k]
        if isinstance(v, list):
            out.append(f"{k}: [{', '.join(yaml_scalar(x) for x in v)}]\n")
        else:
            out.append(f"{k}: {yaml_scalar(v)}\n")
    out.append("---\n")
    return "".join(out)


# --------------------------------------------------------------------------- #
# SCHEMA.md machine block: schema version + tag taxonomy
# --------------------------------------------------------------------------- #


def load_schema(schema_text: str) -> tuple[str | None, set[str]]:
    """(schema_version, tags) from the machine-readable block in SCHEMA.md.

    The block is the first fenced yaml block carrying both a `schema_version`
    and a `tags` mapping. Prose elsewhere in the file is ignored - that is the
    point. An inline `tags: [a, b]` list is NOT the taxonomy and causes the block
    to be skipped, which yields an empty taxonomy and flags every page; the
    reference doc calls this out as the failure mode to watch for.
    """
    for block in SCHEMA_BLOCK_RE.findall(schema_text):
        version: str | None = None
        tags: list[str] = []
        in_tags = False
        for line in block.splitlines():
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            indented = line[0] in " \t"
            key, sep, val = line.partition(":")
            if not sep:
                continue
            key, val = key.strip(), val.strip()
            if indented:
                if in_tags and val == "":
                    tags.append(key)
            else:
                in_tags = key == "tags"
                if key == "schema_version":
                    version = val
        if version is not None and tags:
            return version, set(tags)
    return None, set()


# --------------------------------------------------------------------------- #
# Links
# --------------------------------------------------------------------------- #


def norm_key(value: str) -> str:
    """Case- and separator-insensitive key: 'Hermes Agent' -> 'hermes-agent'."""
    return re.sub(r"[^a-z0-9]+", "-", str(value).lower()).strip("-")


def wikilinks_in(text: str) -> set[str]:
    """Wikilinks in prose only - code spans and fenced blocks are excluded.

    Pages that *document* wikilink syntax contain literal examples; without this
    every such page self-reports a broken link on every run.
    """
    text = FENCE_RE.sub("", text)
    text = INLINE_CODE_RE.sub("", text)
    return {t.strip() for t in LINK_RE.findall(text)}


def build_link_map(pages: dict, archived: dict) -> dict[str, str]:
    """Resolve a link target to a slug. Precedence: path slug > basename >
    title > alias. Live pages are registered before archived ones, so a live page
    wins a name collision with an archived page - which is what you want, and is
    exactly the case where a link silently keeps resolving after an archive.
    """
    link_map: dict[str, str] = {}

    def put(key: str, slug: str) -> None:
        if key and key not in link_map:
            link_map[key] = slug

    for group in (pages, archived):
        for slug in sorted(group):
            put(norm_key(slug), slug)
            put(norm_key(Path(slug).stem), slug)
        for slug in sorted(group):
            put(norm_key(group[slug]["title"]), slug)
        for slug in sorted(group):
            for alias in group[slug]["aliases"]:
                put(norm_key(alias), slug)
    return link_map


