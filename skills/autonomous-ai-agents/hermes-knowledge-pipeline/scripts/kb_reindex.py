def render_index(pages: dict, archived: dict, report: dict) -> str:
    """Deterministic: no timestamps, so an unchanged vault produces identical
    bytes and git sees no churn."""
    canonical = {d: [] for d in CANONICAL_DIRS}
    pending = []
    work: dict[str, list] = {st: [] for st in WORK_STATUSES}
    for slug in sorted(pages):
        m = pages[slug]
        if m["dir"] == "inbox":
            pending.append(slug)
        elif m["dir"] == WORK_DIR:
            work.setdefault(m["status"], []).append(slug)
        elif m["dir"] in canonical:
            canonical[m["dir"]].append(slug)
    newest = max((m["updated"] for m in pages.values() if m["updated"]), default="-")
    version = report.get("schema_version") or "?"
    total = sum(len(v) for v in canonical.values())

    out = [INDEX_BANNER, "\n# Wiki Index\n\n",
           "> Content catalog, generated from the pages themselves.\n"
           f"> Current: {total} | Pending: {len(pending)} | Archived: {len(archived)} | "
           f"Newest edit: {newest} | Schema v{version}\n\n"]
    for d in CANONICAL_DIRS:
        title = {"entities": "Entities", "concepts": "Concepts",
                 "comparisons": "Comparisons", "queries": "Queries"}[d]
        out.append(f"## {title}\n\n")
        for slug in canonical[d]:
            m = pages[slug]
            note = f" — {m['summary']}" if m["summary"] else ""
            out.append(f"- [[{slug}]]{note}\n")
        out.append("\n")

    out.append("## Pending proposals (`inbox/`)\n\n")
    if pending:
        out.append("Not yet canonical, and not authoritative until promoted. Promote = move to\n"
                   "the type directory, set `status: approved`, append to `log.md`.\n"
                   "Reject = delete and log the reason.\n\n")
        for slug in pending:
            m = pages[slug]
            note = f" — {m['summary']}" if m["summary"] else ""
            out.append(f"- [[{slug}]]{note}\n")
    else:
        out.append("None.\n")

    out.append("\n## Archived iterations (`_archive/`)\n\n")
    if archived:
        out.append("Superseded and retired. Kept so a later iteration can see what was\n"
                   "believed before and why it changed. Not authoritative — do not cite as\n"
                   "current. Hidden from Obsidian search and graph by design.\n\n")
        for slug in sorted(archived, key=lambda s: archived[s]["archived"] or "", reverse=True):
            m = archived[slug]
            when = m["archived"] or "-"
            succ = m["superseded_by"] or "(no successor recorded)"
            out.append(f"- `{when}` [[{slug}]] → superseded by [[{succ}]]"
                       + (f" — {m['summary']}" if m["summary"] else "") + "\n")
    else:
        out.append("None.\n")

    # Work in flight. Listed here so the catalog stays complete, but the
    # interactive surface for it is the Bases views in HOME.md.
    total_work = sum(len(v) for v in work.values())
    out.append(f"\n## Work in flight (`{WORK_DIR}/`) — {total_work}\n\n")
    if total_work:
        out.append("The supervisor board. Grouped by `status`; `priority`, `owner` and\n"
                   "`topic` are the board's other axes. Edit these in Obsidian or here —\n"
                   "the board reads the same frontmatter.\n\n")
        for st in WORK_STATUSES:
            if not work.get(st):
                continue
            out.append(f"**{st}** ({len(work[st])})\n\n")
            for slug in work[st]:
                m = pages[slug]
                out.append(f"- [[{slug}]] `{m['priority'] or '-'}` "
                           f"({m['owner'] or '-'}) — {m['summary']}\n")
            out.append("\n")
    else:
        out.append("None.\n")
    return "".join(out)



def render_orient(root: Path, pages: dict, archived: dict, report: dict) -> dict:
    pending = [{"slug": s, "title": pages[s]["title"], "updated": pages[s]["updated"]}
               for s in report["state"]["proposed_pages"]]
    by_dir: dict[str, int] = {}
    for m in pages.values():
        by_dir[m["dir"]] = by_dir.get(m["dir"], 0) + 1
    log_path = root / "log.md"
    log_text = log_path.read_text(encoding="utf-8", errors="replace") if log_path.is_file() else ""
    return {
        "root": str(root),
        "schema_version": report.get("schema_version"),
        "taxonomy": report.get("taxonomy"),
        "page_count": len(pages),
        "by_directory": by_dir,
        "canonical_count": sum(v for k, v in by_dir.items() if k != "inbox"),
        "archived_count": len(archived),
        "pending_proposals": pending,
        "state": report["state"],
        "findings": report["findings"],
        "newest_edit": max((m["updated"] for m in pages.values() if m["updated"]), default=None),
        "recent_log": [{"date": d, "action": a, "subject": s}
                       for d, a, s in LOG_ENTRY_RE.findall(log_text)][-6:],
    }


def print_orient(orient: dict) -> None:
    findings = sum(len(v) for v in orient["findings"].values())
    state = orient["state"]
    print(f"KB ORIENTATION  (schema v{orient['schema_version'] or '?'}, "
          f"kb_reindex {__version__})")
    print(f"  root      : {orient['root']}")
    print(f"  pages     : {orient['canonical_count']} current, "
          f"{len(orient['pending_proposals'])} pending, "
          f"{orient['archived_count']} archived | newest edit "
          f"{orient['newest_edit'] or '-'}")
    print(f"  by dir    : " + ", ".join(f"{k} {v}" for k, v in sorted(orient["by_directory"].items())))
    print(f"  state     : contested {len(state['contested_pages'])}, "
          f"low-confidence {len(state['low_confidence_pages'])}, "
          f"stale {len(state['stale_pages'])}, "
          f"unlinked-to {len(state.get('zero_inbound_pages', []))}")
    work = state.get("work_by_status") or {}
    if work:
        print("  work      : " + ", ".join(f"{k} {len(v)}" for k, v in work.items() if v)
              + (f"  | needs human: {len(state.get('work_needing_human') or [])}"
                 if state.get("work_needing_human") else ""))
    print(f"  findings  : {findings}")
    for entry in orient["recent_log"][-3:]:
        print(f"  recent    : {entry['date']} {entry['action']} | {entry['subject'][:70]}")
    if orient["pending_proposals"]:
        print("  review    : " + ", ".join(p["slug"].split("/")[-1]
                                          for p in orient["pending_proposals"]))


