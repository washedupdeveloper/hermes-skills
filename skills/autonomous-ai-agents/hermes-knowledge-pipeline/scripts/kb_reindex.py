def resolve_root() -> Path:
    """Vault root: env > kb_root.py's OS default > cwd.

    A cron script inherits the scheduler's environment, so WIKI_PATH is normally
    present; the kb_root fallback matters when the script is run by hand.
    """
    for var in ("HERMES_KB_ROOT", "WIKI_PATH", "OBSIDIAN_VAULT_PATH"):
        val = os.environ.get(var)
        if val:
            return Path(os.path.expanduser(val))
    try:
        import kb_root  # co-located when installed under $HERMES_HOME/scripts/
        resolved, _ = kb_root.resolve()
        if resolved:
            return Path(resolved)
    except Exception:
        pass
    return Path.cwd()


def write_if_changed(path: Path, content: str) -> bool:
    """Write only on real change, so an unchanged vault does not touch mtimes."""
    if path.is_file() and path.read_text(encoding="utf-8", errors="replace") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    root = Path(args[0]).expanduser() if args else resolve_root()
    if not root.is_dir():
        print(f"kb_reindex: root not found: {root}", file=sys.stderr)
        return 1

    pages, archived = build(root)
    report = lint(root, pages, archived)
    orient = render_orient(root, pages, archived, report)

    if "--orient" in sys.argv:
        print_orient(orient)
        return 0

    meta = root / "_meta"
    meta.mkdir(exist_ok=True)
    (meta / "kb-index.json").write_text(json.dumps(
        {"kb_reindex": __version__, "root": str(root), "page_count": len(pages),
         "archived_count": len(archived), "schema_version": report.get("schema_version"),
         "pages": pages, "archived": archived},
        indent=2, sort_keys=True), encoding="utf-8")
    (meta / "orient.json").write_text(
        json.dumps(orient, indent=2, sort_keys=True), encoding="utf-8")
    write_if_changed(root / "index.md", render_index(pages, archived, report))

    total = sum(len(v) for v in report["findings"].values())
    if total:
        print(f"KB LINT: {total} finding(s) across {len(pages)} current pages"
              + (f" + {len(archived)} archived" if archived else ""))
        for key, val in report["findings"].items():
            print(f"  {key}: {json.dumps(val)[:400]}")
        if report["state"]["proposed_pages"]:
            print(f"  (state) pending_proposals: "
                  f"{len(report['state']['proposed_pages'])} awaiting review")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
