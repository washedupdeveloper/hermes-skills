# Build
# --------------------------------------------------------------------------- #


def body_hash(body: str) -> str:
    """sha256 over the LF-normalised body.

    Line-ending churn is NOT drift. A vault edited from Windows (Obsidian,
    Notepad, git without eol=lf) and from WSL2/Linux otherwise produces
    CRLF-vs-LF differences that would fire a false immutability alarm on every
    platform hop. The hash is defined over content, not bytes-on-disk.
    """
    normalised = body.replace("\r\n", "\n").replace("\r", "\n")
    return hashlib.sha256(normalised.encode("utf-8")).hexdigest()


def clip(text: str, limit: int = 110) -> str:
    """Trim to a word boundary with an ellipsis - mid-word cuts read as corruption."""
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(" ,;:—-")
    return (cut or text[:limit]) + "…"


def first_line_summary(body: str) -> str:
    """One-line summary for the generated index, taken from the page itself."""
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith(("#", ">", "---", "|", "!")):
            continue
        s = re.sub(r"`([^`]*)`", r"\1", s)
        s = re.sub(r"\*\*|__", "", s)
        s = re.sub(r"\[\[([^\]|]+)(?:\|[^\]]*)?\]\]", r"\1", s)
        s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)
        return clip(s.strip())
    return ""


def _read_page(p: Path, root: Path, dirname: str) -> tuple[str, dict]:
    text = p.read_text(encoding="utf-8", errors="replace")
    fm, body = parse_frontmatter(text)
    slug = p.relative_to(root).with_suffix("").as_posix()
    return slug, {
        "path": p.relative_to(root).as_posix(),
        "dir": dirname,
        "title": str(fm.get("title") or p.stem.replace("-", " ").title()),
        "type": str(fm.get("type") or ""),
        "tags": as_list(fm.get("tags")),
        "aliases": as_list(fm.get("aliases")),
        "sources": as_list(fm.get("sources")),
        "updated": str(fm.get("updated") or ""),
        "confidence": str(fm.get("confidence") or ""),
        "contested": str(fm.get("contested") or "").lower() in ("true", "yes", "1"),
        "status": str(fm.get("status") or "approved"),
        "schema_version": str(fm.get("schema_version") or ""),
        "priority": str(fm.get("priority") or ""),
        "owner": str(fm.get("owner") or ""),
        "topic": str(fm.get("topic") or ""),
        "blocked_by": as_list(fm.get("blocked_by")),
        "council_run": str(fm.get("council_run") or ""),
        # Council-run properties, so the board can group and filter on them.
        "generated": str(fm.get("generated") or "").lower() in ("true", "yes", "1"),
        "project": str(fm.get("project") or ""),
        "verdict": str(fm.get("verdict") or ""),
        "aggregate": fm.get("aggregate") if fm.get("aggregate") is not None else "",
        "threshold": fm.get("threshold") if fm.get("threshold") is not None else "",
        "superseded_by": str(fm.get("superseded_by") or ""),
        "supersedes": as_list(fm.get("supersedes")),
        "archived": str(fm.get("archived") or ""),
        "missing_fields": [f for f in REQUIRED_FM if f not in fm],
        "summary": first_line_summary(body),
        "lines": body.count("\n") + 1,
        "outbound": [],
        "inbound": [],
    }


def build(root: Path) -> tuple[dict, dict]:
    """(live_pages, archived_pages). Archived pages are built the same way but
    kept in their own mapping so live-only rules (orphans, status/location,
    type/directory) never fire on them."""
    pages: dict[str, dict] = {}
    for d in PAGE_DIRS:
        base = root / d
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*.md")):
            slug, meta = _read_page(p, root, d)
            pages[slug] = meta

    archived: dict[str, dict] = {}
    abase = root / ARCHIVE_DIR
    if abase.is_dir():
        for p in sorted(abase.rglob("*.md")):
            slug, meta = _read_page(p, root, ARCHIVE_DIR)
            archived[slug] = meta

    link_map = build_link_map(pages, archived)
    for group in (pages, archived):
        for slug, meta in group.items():
            src = (root / meta["path"]).read_text(encoding="utf-8", errors="replace")
            targets = wikilinks_in(src)
            meta["outbound"] = sorted(targets)
            for t in targets:
                hit = link_map.get(norm_key(t))
                if hit and hit != slug and hit in group:
                    group[hit]["inbound"].append(slug)
    return pages, archived


# --------------------------------------------------------------------------- #
# Lint: findings (defects) vs state (normal)
# --------------------------------------------------------------------------- #


def lint(root: Path, pages: dict, archived: dict) -> dict:
    schema = root / "SCHEMA.md"
    schema_text = schema.read_text(encoding="utf-8", errors="replace") if schema.is_file() else ""
    schema_version, taxonomy = load_schema(schema_text)
    link_map = build_link_map(pages, archived)
    log = root / "log.md"
    log_text = log.read_text(encoding="utf-8", errors="replace") if log.is_file() else ""
    today = datetime.date.today()

    broken, orphans, bad_tags, over, drift, unprovenanced = [], [], [], [], [], []
    missing_fm, status_odd, type_odd, unlogged, outdated = [], [], [], [], []
    contested, low_conf, stale = [], [], []
    to_archived, no_successor, ghost_successor, not_reciprocated = [], [], [], []
    work_odd, work_extra = [], []

    for slug, m in pages.items():
        for t in m["outbound"]:
            hit = link_map.get(norm_key(t))
            if hit is None:
                broken.append({"page": slug, "link": t})
            elif hit in archived:
                # Resolves, but points at a retired iteration. The successor is
                # usually what the reader wants.
                to_archived.append({"page": slug, "link": t, "archived_slug": hit,
                                    "successor": archived[hit]["superseded_by"] or None})
        # Orphans are checked for CANONICAL pages only. A canonical page must be
        # reachable or it is invisible. An inbox proposal is already surfaced by
        # the generated index and may legitimately be a stub.
        if m["dir"] in CANONICAL_DIRS and not m["inbound"] and not m["outbound"]:
            orphans.append(slug)
        if m["tags"] and taxonomy and not set(m["tags"]) & taxonomy:
            bad_tags.append({"page": slug, "tags": m["tags"]})
        if m["lines"] > MAX_LINES:
            over.append({"page": slug, "lines": m["lines"]})
        if m["missing_fields"]:
            missing_fm.append({"page": slug, "fields": m["missing_fields"]})

        if m["dir"] == "inbox" and m["status"] != "proposed":
            status_odd.append({"page": slug, "status": m["status"],
                               "expected": "proposed (it is in inbox/)"})
        if m["dir"] in CANONICAL_DIRS and m["status"] == "proposed":
            status_odd.append({"page": slug, "status": "proposed",
                               "expected": "approved, or move it back to inbox/"})

        # ---- work items: the board's fields must be present and in-domain ----
        if m["dir"] == WORK_DIR:
            if m["type"] and m["type"] != "work":
                work_odd.append({"page": slug, "type": m["type"], "expected": "work"})
            for field in WORK_REQUIRED:
                if field not in m or not m[field]:
                    work_extra.append({"page": slug, "missing": field})
            if m["status"] not in WORK_STATUSES:
                work_odd.append({"page": slug, "status": m["status"],
                                 "expected": "| ".join(WORK_STATUSES)})
            if m["priority"] and m["priority"] not in WORK_PRIORITIES:
                work_odd.append({"page": slug, "priority": m["priority"],
                                 "expected": "| ".join(WORK_PRIORITIES)})
            if m["owner"] and m["owner"] not in WORK_OWNERS:
                work_odd.append({"page": slug, "owner": m["owner"],
                                 "expected": "| ".join(WORK_OWNERS)})
            if m["status"] == "blocked" and not m["blocked_by"]:
                work_extra.append({"page": slug, "missing": "blocked_by (status is blocked)"})
        if m["dir"] in CANONICAL_DIRS and m["type"]:
            expected = DIR_TYPE[m["dir"]]
            if m["type"] != expected:
                type_odd.append({"page": slug, "type": m["type"], "dir": m["dir"],
                                 "expected": expected})

        if m["status"] == "proposed" and m["title"] not in log_text \
                and Path(slug).stem not in log_text:
            unlogged.append({"page": slug, "title": m["title"]})

        if m["contested"]:
            contested.append(slug)
        if m["confidence"] == "low":
            low_conf.append(slug)
        if m["updated"]:
            try:
                if (today - datetime.date.fromisoformat(m["updated"])).days > STALE_DAYS:
                    stale.append({"page": slug, "days": (today - datetime.date.fromisoformat(m["updated"])).days})
            except ValueError:
                pass

        # A live page must not claim to supersede something that no longer exists.
        # Resolved through link_map, not dict membership: an archived slug is a full
        # path (`_archive/entities/x`) while the reference is written as `x`.
        for target in m["supersedes"]:
            if link_map.get(norm_key(target)) is None:
                ghost_successor.append({"page": slug, "supersedes": target})

    # ---- archive integrity: an archived iteration must record its successor ----
    for slug, m in archived.items():
        succ = m["superseded_by"]
        if not succ:
            no_successor.append({"page": slug,
                                 "why": "archived without superseded_by - a retired "
                                        "iteration must say what replaced it"})
            continue
        hit = link_map.get(norm_key(succ))
        if hit is None:
            ghost_successor.append({"page": slug, "superseded_by": succ})
            continue
        # Reciprocity: the successor should name what it replaced. Compared by
        # resolution, so `supersedes: [retired-c]` matches `_archive/.../retired-c`.
        if hit in pages:
            if not any(link_map.get(norm_key(x)) == slug for x in pages[hit]["supersedes"]):
                not_reciprocated.append({"archived": slug, "successor": hit})

    for rdir in RAW_DIRS:
        base = root / rdir
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*.md")):
            rel = p.relative_to(root).as_posix()
            fm, body = parse_frontmatter(p.read_text(encoding="utf-8", errors="replace"))
            stored = str(fm.get("sha256") or "").strip()
            if not stored:
                unprovenanced.append({"file": rel, "missing": "sha256"})
                continue
            actual = body_hash(body)
            if stored != actual:
                drift.append({"file": rel, "stored": stored[:12], "actual": actual[:12]})
            if not str(fm.get("source_url") or "").strip():
                unprovenanced.append({"file": rel, "missing": "source_url"})

    # Every canonical page must be attributable in the append-only log. A page that
    # appears in no log entry cannot be traced to a source, a session or a decision.
    # Checked by title, stem and full slug so any reasonable log phrasing passes; this
    # is deliberately lenient, because a check that fires on a well-kept vault is worse
    # than no check at all.
    never_logged = []
    for slug, m in pages.items():
        if m["dir"] not in CANONICAL_DIRS:
            continue
        if m["title"] in log_text or Path(slug).stem in log_text or slug in log_text:
            continue
        never_logged.append({"page": slug, "title": m["title"]})

    if schema_version is not None:
        for slug, m in pages.items():
            if m["schema_version"] and m["schema_version"] != schema_version:
                outdated.append({"page": slug, "page_version": m["schema_version"],
                                 "schema_version": schema_version})

    # ---- a whole page directory disappearing is never legitimate ----
    # Promote and archive MOVE a page between directories; nothing in the pipeline
    # removes a directory. So a page directory that held pages last run and is now
    # gone from disk means something outside the pipeline deleted it - and because the
    # vault is silent when healthy, that would otherwise be invisible. The previous
    # index is the memory that makes this detectable with no extra dependency: it
    # already records which directory every page lived in.
    prev = root / "_meta" / "kb-index.json"
    vanished: list[dict] = []
    if prev.is_file():
        try:
            before = json.loads(prev.read_text(encoding="utf-8")) or {}
        except Exception:
            before = {}
        was: dict[str, int] = {}
        for meta in (before.get("pages") or {}).values():
            d = str(meta.get("dir") or "")
            if d:
                was[d] = was.get(d, 0) + 1
        for d, n in sorted(was.items()):
            if not (root / d).is_dir():
                vanished.append({"dir": d, "pages_last_run": n,
                                 "hint": "restore with `git checkout -- " + d + "/`"})

    findings = {
        "broken_links": broken,
        "orphan_pages": orphans,
        "tags_outside_taxonomy": bad_tags,
        "pages_over_%d_lines" % MAX_LINES: over,
        "missing_frontmatter_fields": missing_fm,
        "status_contradicts_location": status_odd,
        "work_item_status_or_priority_invalid": work_odd,
        "work_item_missing_board_field": work_extra,
        "page_directory_vanished": vanished,
        "type_contradicts_directory": type_odd,
        "proposals_missing_log_entry": unlogged,
        "canonical_page_never_logged": never_logged,
        "links_to_archived_page": to_archived,
        "archived_without_successor": no_successor,
        "supersession_target_missing": ghost_successor,
        "supersedes_not_reciprocated": not_reciprocated,
        "raw_sha256_drift": drift,
        "raw_missing_provenance": unprovenanced,
        "schema_version_behind": outdated,
    }
    state = {
        "proposed_pages": sorted(s for s, m in pages.items() if m["status"] == "proposed"),
        "contested_pages": sorted(contested),
        "low_confidence_pages": sorted(low_conf),
        "stale_pages": stale,
        "archived_pages": sorted(archived),
        "work_by_status": {st: sorted(s for s, m in pages.items()
                                       if m["dir"] == WORK_DIR and m["status"] == st)
                           for st in WORK_STATUSES},
        "work_needing_human": sorted(s for s, m in pages.items()
                                     if m["dir"] == WORK_DIR
                                     and (m["owner"] == "human" or m["status"] == "blocked")),
        # A page nothing links TO is findable only from the generated index. That is a
        # discoverability weakness, not a defect - a self-contained page may legitimately
        # have no inbound links - so it is STATE. Reporting it as a finding would make a
        # healthy vault noisy, which is how a check gets ignored.
        "zero_inbound_pages": sorted(s for s, m in pages.items() if not m["inbound"]),
    }
    return {"schema_version": schema_version, "taxonomy": sorted(taxonomy),
            "findings": {k: v for k, v in findings.items() if v}, "state": state}


